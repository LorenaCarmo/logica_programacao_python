# CRIE UM ALGORITMO QUE LEIA UM NUMERO E MOSTRE O SEU DOBRO, TRIPLO E RAIZ QUADRADA

n = int(input('Digite um número inteiro: '))
print(f'O dobro do número digitado é: {n*2}, o triplo é {n*3} e a raiz quadrada é: {n**(1/2)}.')

# Raiz quadrada → n ** (1/2)
# Raiz cúbica → n ** (1/3)
# Raiz quarta → n ** (1/4)
# Raiz quinta → n ** (1/5)
